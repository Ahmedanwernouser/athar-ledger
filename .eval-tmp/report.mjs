// report.mjs — turns raw results into eval/RESULTS.md (Arabic).
const pct = (a, b) => (b ? (100 * a / b) : 0);
const f1 = x => x.toFixed(1);
function agg(rows, fn) {
  const v = rows.map(fn); const mean = v.reduce((a, b) => a + b, 0) / v.length;
  return { mean, min: Math.min(...v), max: Math.max(...v) };
}
const show = a => `${f1(a.mean)} (${f1(a.min)}–${f1(a.max)})`;
const showN = a => `${a.mean.toFixed(1)} (${a.min}–${a.max})`;

export function report(results, { seeds, wers, corpus }) {
  const systems = [...new Set(results.map(r => r.system))];
  const L = [];
  const one = results[0];
  const items = k => one.m[k][0];
  L.push("# نتائج القياس — محرك المطابقة على محاضرات مُركَّبة وضجيج تفريغ **مُحاكى**\n");
  L.push("> **اقرأ هذا أولًا.** هذه الأرقام تقيس **محرك المطابقة وحده** على نصوص مُركَّبة آليًا ثم مُشوَّهة بضجيج يحاكي أخطاء التفريغ الصوتي. " +
    "هي **ليست** قياسًا لأداء نظام تفريغ حقيقي (Whisper) على صوت حقيقي، ولا تُعرض على أنها كذلك. القياس على تسجيلات حقيقية يُجرى بـ `eval/real.mjs` بعد توفّر التسجيلات.\n");
  L.push("## الإعداد\n");
  L.push(`- المدونة (الأساسية فقط، بلا حزم الكتب): ${corpus.N.toLocaleString("en")} مقطعًا (${corpus.NQ.toLocaleString("en")} آية + ${(corpus.N - corpus.NQ).toLocaleString("en")} حديثًا من تسعة كتب).`);
  L.push(`- ${seeds.length} محاضرات مُركَّبة مستقلة (بذور عشوائية: ${seeds.join("، ")}) — البذرة 101 (مع ٢٤ اقتباسًا بالمعنى للتطوير) استُخدمت لضبط العتبات والإعدادات ولا تدخل في هذه الأرقام.`);
  L.push(`- في كل محاضرة: ${items("vq")} استشهادًا قرآنيًا حرفيًا (١–٣ آيات)، ${items("vh")} حديثًا حرفيًا، ${items("ph")} حديثًا مع تغيير في الألفاظ (حذف/استبدال/زيادة)، ` +
    `${one.r.parN} اقتباسًا بالمعنى (صياغة المساعد، من المجموعة المحجوزة)، ${one.r.oocN} حديثًا **خارج المدونة**، ${one.r.cueN} عبارة استشهاد بلا اقتباس، وبينها كلام حشو (≈ ${one.words.toLocaleString("en")} كلمة).`);
  L.push("- «خارج المدونة»: حديث حقيقي يُحذف من المدونة هو وكل رواياته وكل مقطع يشاركه أي أربع كلمات متتالية؛ فلا يبقى في المدونة نص يطابقه.");
  L.push("- الضجيج: استبدال حروف (≈٧٠٪ منه صوتي مثل ص/س، و≈٣٠٪ عشوائي لا يتوقعه المحرك)، حذف/زيادة حرف، حذف كلمة، زيادة كلمة، شطر كلمة، لصق كلمتين. النسبة = احتمال إصابة كل كلمة.");
  L.push("- الأرقام: المتوسط (الأدنى–الأعلى) عبر المحاضرات.\n");
  L.push("### التعريفات\n");
  L.push("- **الاكتشاف**: استشهاد نصي (حرفي أو جزئي) يغطي ≥٥٠٪ من موضع الاقتباس الحقيقي.");
  L.push("- **المصدر الأول صحيح**: المصدر المعروض أولًا هو مقطع يحتوي النص المقتبس فعلًا (من بين ما اكتُشف).");
  L.push("- **التصنيف صحيح**: حرفي/مخلوط كما بُني الاقتباس (من بين ما اكتُشف). الضجيج يحوّل بعض «الحرفي» إلى «مخلوط» — وهذا محسوب خطأً هنا.");
  L.push("- **أخطاء حرجة** (عدد لكل محاضرة): (أ) استشهاد نصي بمصدر لا يحتوي النص، (ب) وصف أغلب نص خارج المدونة بأنه «مطابق حرفيًا»، (ج) استشهاد نصي داخل كلام الحشو.");
  L.push("- **الامتناع الصحيح**: نسبة أحاديث «خارج المدونة» التي لم يُنسب لها أي تطابق حرفي يغطي أغلبها.");
  L.push("- **بالمعنى**: ٢٦ اقتباسًا بالمعنى لم تُستخدم في اختيار الإعدادات (المجموعة المحجوزة). يُحسب هل الحديث المقصود هو أول اقتراح يعرضه النظام عند ذلك الموضع، أو ضمن أول ٣، أو أول ٥. هذه **اقتراحات للمراجعة**، لا مطابقات. الأنظمة المرجعية B0/B1 لا تعرض قوائم اقتراحات، فتُحسب لها المطابقة النصية فقط.\n");

  for (const wer of wers) {
    L.push(`## ضجيج ${Math.round(wer * 100)}٪\n`);
    L.push("| النظام | اكتشاف القرآن | اكتشاف الحديث الحرفي | اكتشاف الحديث المغيَّر | المصدر الأول صحيح | التصنيف صحيح | أخطاء حرجة | الامتناع الصحيح | بالمعنى: المصدر أول اقتراح | بالمعنى: ضمن أول ٣ | بالمعنى: ضمن أول ٥ |");
    L.push("|---|---|---|---|---|---|---|---|---|---|---|");
    for (const s of systems) {
      const rows = results.filter(r => r.system === s && r.wer === wer);
      if (!rows.length) continue;
      const det = k => agg(rows, r => pct(r.m[k][1], r.m[k][0]));
      const top1 = agg(rows, r => pct(r.m.vq[2] + r.m.vh[2] + r.m.ph[2], r.m.vq[1] + r.m.vh[1] + r.m.ph[1]));
      const cls = agg(rows, r => pct(r.r.classOK, r.r.classN));
      const crit = agg(rows, r => r.r.critWrongSource + r.r.critOOC + r.r.critFiller);
      const abst = agg(rows, r => pct(r.r.oocN - r.r.critOOC, r.r.oocN));
      const par = agg(rows, r => pct(r.r.parTop1, r.r.parN)), par3 = agg(rows, r => pct(r.r.parTop3, r.r.parN)), par5 = agg(rows, r => pct(r.r.parTop5, r.r.parN));
      L.push(`| ${s} | ${show(det("vq"))} | ${show(det("vh"))} | ${show(det("ph"))} | ${show(top1)} | ${show(cls)} | ${showN(crit)} | ${show(abst)} | ${show(par)} | ${show(par3)} | ${show(par5)} |`);
    }
    L.push("");
  }
  const eng = systems[0];
  L.push("## تفاصيل المحرك الكامل\n");
  L.push("| الضجيج | خطأ مصدر | «خارج المدونة» وُصف حرفيًا | استشهاد في الحشو | «خارج المدونة» له تطابق جزئي برواية أخرى | عبارة استشهاد بلا اقتباس → بلا تطابق | فحص النسبة المنطوقة («رواه …») صحيح | خطأ بداية الموضع (كلمات) | زمن التحليل (ث) |");
  L.push("|---|---|---|---|---|---|---|---|---|");
  for (const wer of wers) {
    const rows = results.filter(r => r.system === eng && r.wer === wer);
    L.push(`| ${Math.round(wer * 100)}٪ | ${showN(agg(rows, r => r.r.critWrongSource))} | ${showN(agg(rows, r => r.r.critOOC))} | ${showN(agg(rows, r => r.r.critFiller))} | ${showN(agg(rows, r => r.r.oocPartial))} من ${rows[0].r.oocN} | ${show(agg(rows, r => pct(r.r.cueClean, r.r.cueN)))}٪ | ${show(agg(rows, r => pct(r.r.attrOK, r.r.attrN)))}٪ | ${agg(rows, r => r.r.startErr / Math.max(1, r.r.startN)).mean.toFixed(2)} | ${(agg(rows, r => r.ms).mean / 1000).toFixed(1)} |`);
  }
  L.push("");
  L.push("## ما الذي تقوله هذه الأرقام — وما الذي لا تقوله\n");
  L.push("- **تقول**: على نص نظيف أو قليل الضجيج، المحرك يكتشف الاستشهادات الحرفية ويربطها بمصدرها مع أخطاء حرجة قليلة جدًا، ويمتنع عن نسبة نص خارج المدونة.");
  L.push("- **تقول**: التسامح مع أخطاء التفريغ (الطيّ الصوتي + لصق/شطر الكلمات) هو ما يُبقي الاكتشاف مرتفعًا مع ارتفاع الضجيج؛ قارن سطر «بلا تسامح».");
  L.push("- **تقول**: البحث الهجين (ألفاظ + متجهات مدرَّبة على المدونة + إعادة ترتيب) يرفع نسبة وجود الحديث المقصود بين اقتراحات «بالمعنى» مقارنة بالألفاظ وحدها؛ قارن سطر «بلا متجهات».");
  L.push("- **تقول بوضوح**: حتى مع ذلك، أغلب الاقتباسات بالمعنى لا يظهر مصدرها أولَ اقتراح، والأداة لا تجزم فيها بشيء: تبقى «لم يُعثر على لفظه» مع اقتراحات. والمتجهات تضعف مع ضجيج التفريغ لأن الكلمة المشوَّهة تخرج من مفرداتها. هذا حدٌّ معلن.");
  L.push("- **لا تقول**: كم سيخطئ Whisper فعلًا في نص عربي فصيح بتجويد أو بلهجة. نموذج الضجيج من تصميمنا، وجزء منه (الاستبدال الصوتي) هو نفسه ما صُمّم المحرك لتحمّله — فالأرقام عند الضجيج المرتفع متفائلة على الأرجح.");
  L.push("- **لا تقول**: شيئًا عن صحة الحديث. المحرك يقارن ألفاظًا بمدونة؛ لا يحكم على ثبوت.\n");
  L.push("## إعادة الإنتاج\n```bash\nnode eval/run.mjs      # يكتب eval/results.json و eval/RESULTS.md\nnode --test tests/*.test.mjs\n```\n");
  return L.join("\n");
}
